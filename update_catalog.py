# First, read existing rows
with open(csv_path, 'r', encoding='utf-8', errors='ignore') as f:
    lines = f.readlines()

existing_rows = []
reader = csv.reader("".join(lines).splitlines())
max_id = 0
existing_names = set()

for r in reader:
    if not r or not any(r):
        continue
    first = r[0].strip()
    if first.isdigit():
        item_id = int(first)
        if item_id > max_id:
            max_id = item_id
        name = r[2].strip() if len(r) > 2 else ""
        existing_names.add(name.upper())
        existing_rows.append(r)

print(f"Existing valid rows: {len(existing_rows)}, Max ID: {max_id}")

